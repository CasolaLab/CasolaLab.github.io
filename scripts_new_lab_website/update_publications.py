"""Regenerate data/publications.js for the lab website from Europe PMC.

Queries Europe PMC for papers authored by Casola C with a Texas, Indiana,
Pisa or Arlington affiliation, drops corrections/errata and preprints that
duplicate a published record, and writes a JS data file the site reads.

Usage:
    python3 scripts_new_lab_website/update_publications.py [project_root]
"""

import datetime
import html
import json
import os
import re
import sys
import urllib.parse
import urllib.request

QUERY = ('AUTH:"Casola C" AND (AFF:"Texas" OR AFF:"Indiana" '
         'OR AFF:"Pisa" OR AFF:"Arlington")')
# Lab papers the affiliation filter misses (no affiliation indexed). Add
# Europe PMC ids here (PMID, or PPR id for preprints) to include them.
EXTRA_IDS = ["PPR1346484", "PPR566284", "25038751", "21813467"]
API = "https://www.ebi.ac.uk/europepmc/webservices/rest/search"
CORRECTION = re.compile(r"^(author correction|correction|erratum|corrigendum)\b",
                        re.IGNORECASE)


def clean_title(t):
    # Species italics are applied by the site, so source markup is dropped.
    t = re.sub(r"<[^>]+>", "", html.unescape(html.unescape(t)))
    return re.sub(r"\s+", " ", t).strip()


def norm_title(t):
    return re.sub(r"[^a-z0-9]", "", t.lower())


def fetch(query):
    params = {"query": query, "format": "json", "pageSize": 1000,
              "resultType": "lite", "sort": "P_PDATE_D desc"}
    url = API + "?" + urllib.parse.urlencode(params)
    print(f"fetching {url}", file=sys.stderr)
    with urllib.request.urlopen(url, timeout=60) as r:
        data = json.load(r)
    hits = data["resultList"]["result"]
    assert len(hits) == data["hitCount"], (
        f"got {len(hits)} records but hitCount is {data['hitCount']}")
    return hits


def main():
    root = sys.argv[1] if len(sys.argv) > 1 else os.getcwd()
    data_dir = os.path.join(root, "data")
    if not os.path.isdir(data_dir):
        sys.exit(f"error: {data_dir} not found; run from the project root")

    hits = fetch(QUERY)
    have = {h["id"] for h in hits}
    extra = [h for h in fetch(" OR ".join(f"EXT_ID:{i}" for i in EXTRA_IDS))
             if h["id"] in EXTRA_IDS and h["id"] not in have]
    print(f"{len(extra)} extra records added from EXTRA_IDS", file=sys.stderr)
    hits = sorted(hits + extra, key=lambda h: h.get("firstPublicationDate", ""),
                  reverse=True)
    dropped = {"correction/erratum": 0, "preprint of published paper": 0,
               "duplicate record": 0}
    published_titles = {norm_title(h.get("title", "")) for h in hits
                        if h.get("source") != "PPR"}
    seen, pubs = set(), []
    for h in hits:
        title = clean_title(h.get("title", ""))
        if CORRECTION.match(title) or "Published Erratum" in json.dumps(
                h.get("pubTypeList", {})):
            dropped["correction/erratum"] += 1
            continue
        key = h.get("doi") or norm_title(title)
        if h.get("source") == "PPR" and norm_title(title) in published_titles:
            dropped["preprint of published paper"] += 1
            continue
        if key in seen:
            dropped["duplicate record"] += 1
            continue
        seen.add(key)
        pubs.append({
            "title": title.rstrip("."),
            "authors": h.get("authorString", "").rstrip("."),
            "journal": h.get("journalTitle", "") or h.get("bookOrReportDetails", {}).get("publisher", ""),
            "year": int(h["pubYear"]),
            "doi": h.get("doi", ""),
            "pmid": h.get("pmid", ""),
            "date": h.get("firstPublicationDate", ""),
            "preprint": h.get("source") == "PPR",
        })

    n_in, n_out, n_drop = len(hits), len(pubs), sum(dropped.values())
    assert n_in == n_out + n_drop, f"{n_in} in != {n_out} out + {n_drop} dropped"
    for reason, n in dropped.items():
        print(f"dropped {n}: {reason}", file=sys.stderr)
    print(f"{n_in} records in, {n_out} written", file=sys.stderr)

    header = (f"// Generated by scripts_new_lab_website/update_publications.py\n"
              f"// Source: Europe PMC REST API, query: {QUERY}; plus ids {EXTRA_IDS}\n"
              f"// Date: {datetime.date.today().isoformat()}; "
              f"{n_in} records in, {n_out} written, dropped {dropped}\n"
              f"// Do not edit by hand; rerun the script.\n")
    out = os.path.join(data_dir, "publications.js")
    with open(out, "w", encoding="utf-8") as f:
        f.write(header)
        f.write("window.PUBLICATIONS = ")
        json.dump(pubs, f, ensure_ascii=False, indent=1)
        f.write(";\n")
    print(out)


if __name__ == "__main__":
    main()
